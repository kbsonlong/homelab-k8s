package gitops

import (
	"bytes"
	"context"
	"encoding/base64"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"net/url"
	"path"
	"time"

	"github.com/kbsonlong/homelab-k8s/apps/waf-console/internal/config"
)

// Repo 抽象 Git 托管 API，后续可补 GitHub 实现。
type Repo interface {
	Get(ctx context.Context, file string) (content []byte, sha string, err error)
	List(ctx context.Context, dir string) ([]string, error)
	// Commit 写入一个或多个文件；DirectCommit=false 时返回 PR 链接。
	Commit(ctx context.Context, msg string, files map[string][]byte) (ref string, err error)
	Log(ctx context.Context, dir string, limit int) ([]CommitInfo, error)
	ConfigDir() string
}

type CommitInfo struct {
	SHA     string    `json:"sha"`
	Message string    `json:"message"`
	Author  string    `json:"author"`
	Time    time.Time `json:"time"`
	URL     string    `json:"url"`
}

type Gitea struct {
	cfg config.Git
	hc  *http.Client
}

func NewGitea(c config.Git) *Gitea { return &Gitea{cfg: c, hc: &http.Client{Timeout: 15 * time.Second}} }

func (g *Gitea) ConfigDir() string { return g.cfg.ConfigDir }

func (g *Gitea) api(p string) string {
	return fmt.Sprintf("%s/api/v1/repos/%s/%s%s", g.cfg.BaseURL, g.cfg.Owner, g.cfg.Repo, p)
}

func (g *Gitea) do(ctx context.Context, method, u string, body any, out any) error {
	var r io.Reader
	if body != nil {
		b, _ := json.Marshal(body)
		r = bytes.NewReader(b)
	}
	req, _ := http.NewRequestWithContext(ctx, method, u, r)
	req.Header.Set("Authorization", "token "+g.cfg.Token)
	req.Header.Set("Content-Type", "application/json")
	resp, err := g.hc.Do(req)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if resp.StatusCode >= 300 {
		b, _ := io.ReadAll(io.LimitReader(resp.Body, 2048))
		return &HTTPError{Code: resp.StatusCode, Body: string(b)}
	}
	if out != nil {
		return json.NewDecoder(resp.Body).Decode(out)
	}
	return nil
}

type HTTPError struct {
	Code int
	Body string
}

func (e *HTTPError) Error() string { return fmt.Sprintf("gitea %d: %s", e.Code, e.Body) }

func (g *Gitea) Get(ctx context.Context, file string) ([]byte, string, error) {
	var out struct{ Content, SHA string }
	u := g.api("/contents/"+escape(file)) + "?ref=" + url.QueryEscape(g.cfg.Branch)
	if err := g.do(ctx, http.MethodGet, u, nil, &out); err != nil {
		return nil, "", err
	}
	b, err := base64.StdEncoding.DecodeString(out.Content)
	return b, out.SHA, err
}

func (g *Gitea) List(ctx context.Context, dir string) ([]string, error) {
	var out []struct{ Name, Type string }
	u := g.api("/contents/"+escape(dir)) + "?ref=" + url.QueryEscape(g.cfg.Branch)
	if err := g.do(ctx, http.MethodGet, u, nil, &out); err != nil {
		return nil, err
	}
	names := make([]string, 0, len(out))
	for _, e := range out {
		if e.Type == "dir" {
			names = append(names, e.Name)
		}
	}
	return names, nil
}

// Commit 使用 Gitea 的多文件接口 POST /contents，一次提交。
func (g *Gitea) Commit(ctx context.Context, msg string, files map[string][]byte) (string, error) {
	type op struct {
		Operation string `json:"operation"`
		Path      string `json:"path"`
		Content   string `json:"content"`
		SHA       string `json:"sha,omitempty"`
	}
	var ops []op
	for p, c := range files {
		_, sha, err := g.Get(ctx, p)
		o := op{Operation: "create", Path: p, Content: base64.StdEncoding.EncodeToString(c)}
		if err == nil {
			o.Operation, o.SHA = "update", sha
		} else if he, ok := err.(*HTTPError); !ok || he.Code != http.StatusNotFound {
			return "", err
		}
		ops = append(ops, o)
	}
	body := map[string]any{"message": msg, "files": ops, "branch": g.cfg.Branch}
	branch := g.cfg.Branch
	if !g.cfg.DirectCommit {
		branch = fmt.Sprintf("waf-console/%d", time.Now().Unix())
		body["new_branch"] = branch
	}
	var out struct {
		Commit struct {
			SHA     string `json:"sha"`
			HTMLURL string `json:"html_url"`
		} `json:"commit"`
	}
	if err := g.do(ctx, http.MethodPost, g.api("/contents"), body, &out); err != nil {
		return "", err
	}
	if g.cfg.DirectCommit {
		return out.Commit.HTMLURL, nil
	}
	var pr struct {
		HTMLURL string `json:"html_url"`
	}
	err := g.do(ctx, http.MethodPost, g.api("/pulls"), map[string]string{
		"title": msg, "head": branch, "base": g.cfg.Branch,
		"body": "Generated by waf-console. CI (waf-lint) must pass before merge.",
	}, &pr)
	return pr.HTMLURL, err
}

func (g *Gitea) Log(ctx context.Context, dir string, limit int) ([]CommitInfo, error) {
	var out []struct {
		SHA     string `json:"sha"`
		HTMLURL string `json:"html_url"`
		Commit  struct {
			Message string `json:"message"`
			Author  struct {
				Name string    `json:"name"`
				Date time.Time `json:"date"`
			} `json:"author"`
		} `json:"commit"`
	}
	u := g.api(fmt.Sprintf("/commits?sha=%s&path=%s&limit=%d&stat=false",
		url.QueryEscape(g.cfg.Branch), url.QueryEscape(dir), limit))
	if err := g.do(ctx, http.MethodGet, u, nil, &out); err != nil {
		return nil, err
	}
	res := make([]CommitInfo, 0, len(out))
	for _, c := range out {
		res = append(res, CommitInfo{c.SHA, c.Commit.Message, c.Commit.Author.Name, c.Commit.Author.Date, c.HTMLURL})
	}
	return res, nil
}

func escape(p string) string {
	u := url.URL{Path: path.Clean(p)}
	return u.EscapedPath()
}
