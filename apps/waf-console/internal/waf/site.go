package waf

import (
	"fmt"
	"regexp"
	"strings"
)

type Mode string

const (
	ModeMirror Mode = "mirror"
	ModeInline Mode = "inline"
	ModeOff    Mode = "off"
)

type Exclusion struct {
	URI    string `yaml:"uri" json:"uri"`
	Rules  []int  `yaml:"rules" json:"rules"`
	Target string `yaml:"target,omitempty" json:"target,omitempty"` // 空 = 整条规则移除
	Reason string `yaml:"reason" json:"reason"`
	Source string `yaml:"source,omitempty" json:"source,omitempty"` // manual|learning|false-positive
}

type Site struct {
	Name          string      `yaml:"name" json:"name"`
	Host          string      `yaml:"host" json:"host"`
	Mode          Mode        `yaml:"mode" json:"mode"`
	MirrorPercent int         `yaml:"mirrorPercent" json:"mirrorPercent"`
	Paranoia      int         `yaml:"paranoia" json:"paranoia"`
	Anomaly       struct {
		Inbound  int `yaml:"inbound" json:"inbound"`
		Outbound int `yaml:"outbound" json:"outbound"`
	} `yaml:"anomaly" json:"anomaly"`
	SkipPaths  []string    `yaml:"skipPaths,omitempty" json:"skipPaths,omitempty"`
	Exclusions []Exclusion `yaml:"exclusions,omitempty" json:"exclusions,omitempty"`
}

var nameRe = regexp.MustCompile(`^[a-z0-9][a-z0-9-]{0,40}$`)

func (s *Site) Validate() error {
	if !nameRe.MatchString(s.Name) {
		return fmt.Errorf("invalid site name %q", s.Name)
	}
	if s.Host == "" {
		return fmt.Errorf("host required")
	}
	switch s.Mode {
	case ModeMirror, ModeInline, ModeOff:
	default:
		return fmt.Errorf("invalid mode %q", s.Mode)
	}
	if s.Paranoia < 1 || s.Paranoia > 4 {
		return fmt.Errorf("paranoia must be 1..4")
	}
	if s.MirrorPercent < 0 || s.MirrorPercent > 100 {
		return fmt.Errorf("mirrorPercent must be 0..100")
	}
	for _, p := range s.SkipPaths {
		if _, err := regexp.Compile(p); err != nil {
			return fmt.Errorf("skipPath %q: %w", p, err)
		}
	}
	for _, e := range s.Exclusions {
		if strings.ContainsAny(e.URI, "\"\n") || strings.ContainsAny(e.Target, "\"\n ") {
			return fmt.Errorf("exclusion contains illegal characters")
		}
	}
	return nil
}

// 每个站点分配 1000 个例外规则 ID：1000000 + idx*1000 + n
func ruleIDBase(siteIdx int) int { return 1000000 + siteIdx*1000 }

// RenderBeforeCRS 生成 REQUEST-900 阶段的例外规则（与 scripts/waf-render.sh 保持一致）。
func (s *Site) RenderBeforeCRS(siteIdx int) string {
	var b strings.Builder
	id := ruleIDBase(siteIdx)
	fmt.Fprintf(&b, "# generated by waf-console for %s — do not edit (add '# manual' to opt out)\n", s.Name)
	hostCond := fmt.Sprintf(`SecRule REQUEST_HEADERS:Host "@rx ^%s(-shadow)?(:\d+)?$"`, regexp.QuoteMeta(s.Host))
	fmt.Fprintf(&b, "%s \\\n  \"id:%d,phase:1,pass,nolog,setvar:tx.blocking_paranoia_level=%d,setvar:tx.detection_paranoia_level=%d,setvar:tx.inbound_anomaly_score_threshold=%d,setvar:tx.outbound_anomaly_score_threshold=%d\"\n",
		hostCond, id, s.Paranoia, s.Paranoia, s.Anomaly.Inbound, s.Anomaly.Outbound)
	id++
	for _, p := range s.SkipPaths {
		fmt.Fprintf(&b, "SecRule REQUEST_FILENAME \"@rx %s\" \\\n  \"id:%d,phase:1,pass,nolog,ctl:ruleEngine=Off\"\n", p, id)
		id++
	}
	for _, e := range s.Exclusions {
		fmt.Fprintf(&b, "# %s\n", e.Reason)
		for _, r := range e.Rules {
			ctl := fmt.Sprintf("ctl:ruleRemoveById=%d", r)
			if e.Target != "" {
				ctl = fmt.Sprintf("ctl:ruleRemoveTargetById=%d;%s", r, e.Target)
			}
			fmt.Fprintf(&b, "SecRule REQUEST_FILENAME \"@beginsWith %s\" \\\n  \"id:%d,phase:1,pass,nolog,%s\"\n", e.URI, id, ctl)
			id++
		}
	}
	return b.String()
}
